#!/usr/bin/env node
/**
 * gen-items.mjs — regenerate `packages/discord/src/item-names.ts`, the Rust
 * item id → display name table a storage monitor panel uses (the Rust+
 * protocol carries item ids only).
 *
 * Source: the items list maintained by rustplusplus
 * (github.com/alexemanuelol/rustplusplus, `src/staticFiles/items.json`), pinned
 * to one commit so the output is reproducible:
 *
 *   node scripts/gen-items.mjs <commit-sha> ["<game version>"]
 *
 * The source file states no game version; pass what the commit or its pull
 * request says (e.g. "April 2026 force wipe, per alexemanuelol/rustplusplus#527").
 *
 * Pick the latest commit that touched the file:
 *   gh api "repos/alexemanuelol/rustplusplus/commits?path=src/staticFiles/items.json&per_page=1" --jq ".[0].sha"
 *
 * Not part of the build: run it by hand when the game adds items, review the
 * diff, and commit the regenerated table.
 */

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "alexemanuelol/rustplusplus";
const PATH = "src/staticFiles/items.json";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(__dirname, "../packages/discord/src/item-names.ts");

function fail(msg) {
  console.error(`\n[gen-items] ${msg}\n`);
  process.exit(1);
}

const sha = process.argv[2];
const gameVersion = process.argv[3]?.trim() || "not stated by the source";
if (!sha || !/^[0-9a-f]{40}$/.test(sha)) {
  fail(`Usage: node scripts/gen-items.mjs <40-character commit sha of ${REPO}> ["<game version>"]`);
}

async function getJson(url) {
  const res = await fetch(url, { headers: { "User-Agent": "conduit-gen-items" } });
  if (!res.ok) fail(`GET ${url} → HTTP ${res.status}`);
  return res.json();
}

const commit = await getJson(`https://api.github.com/repos/${REPO}/commits/${sha}`);
const commitDate = String(commit?.commit?.committer?.date ?? "").slice(0, 10);
const commitSubject = String(commit?.commit?.message ?? "")
  .split("\n")
  .map((line) => line.trim())
  .filter(Boolean)
  .join(" / ")
  // Qualify upstream's bare `#NNN` pull request references with its repo, so they
  // cannot be read as this repo's.
  .replace(/(^|[^\w/])#(\d+)\b/g, `$1${REPO}#$2`);
const items = await getJson(`https://raw.githubusercontent.com/${REPO}/${sha}/${PATH}`);

if (!items || typeof items !== "object") fail("items.json is not an object");
const entries = [];
for (const [key, value] of Object.entries(items)) {
  const id = Number(key);
  if (!Number.isSafeInteger(id) || String(id) !== key) fail(`not an integer item id: ${key}`);
  const name = typeof value?.name === "string" ? value.name.trim() : "";
  if (!name) fail(`item ${key} has no name`);
  entries.push([id, name]);
}
entries.sort((a, b) => a[0] - b[0]);

const rows = entries.map(([id, name]) => `  [${id}, ${JSON.stringify(name)}],`).join("\n");
const out = `/**
 * Rust item id → display name. GENERATED by \`scripts/gen-items.mjs\`; do not
 * edit by hand, regenerate instead.
 *
 * Source: github.com/${REPO}, \`${PATH}\`
 * Commit: ${sha} (${commitDate})
 * Commit message: "${commitSubject}"
 * Game version: ${gameVersion}
 * Entries: ${entries.length}
 */
export const ITEM_NAMES: ReadonlyMap<number, string> = new Map<number, string>([
${rows}
]);
`;

writeFileSync(outFile, out);
console.log(`[gen-items] wrote ${entries.length} items to ${outFile}`);
